#!/usr/bin/env bash
# Writes tests/unit/wasm_vectors.h: the WASM modules of tests/unit/wasm/ and
# the example apps of wasm-apps/, built with wasm-apps/build.sh's flags
# against wasm-apps/sdk/fc_app.h, as C arrays for test_apps.c.
# Needs clang with the wasm32 target and wasm-ld. Usage: tests/unit/gen-wasm-vectors.sh
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
OUT="$ROOT/tests/unit/wasm_vectors.h"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT
FLAGS=(--target=wasm32 -mcpu=mvp -O2 -nostdlib -Wall -Wextra -Werror -Wno-unused-parameter
       -Wl,--no-entry -Wl,--export=__heap_base -Wl,--export=__data_end -Wl,--stack-first
       -Wl,-z,stack-size=1024 -Wl,--initial-memory=65536 -Wl,--max-memory=65536 -Wl,--strip-all)

build() { # name source include [defines...]
    local name="$1" src="$2" inc="$3"
    shift 3
    clang "${FLAGS[@]}" -I"$inc" "$@" -o "$TMP/$name.wasm" "$src"
}

SDK="$ROOT/wasm-apps/sdk"
for src in "$ROOT"/tests/unit/wasm/*.c; do
    build "$(basename "$src" .c)" "$src" "$SDK"
done
build app_alarm_v1 "$ROOT/wasm-apps/alarm/alarm.c" "$SDK" -DAPP_VERSION=1
build app_alarm_v2 "$ROOT/wasm-apps/alarm/alarm.c" "$SDK" -DAPP_VERSION=2
build app_trend "$ROOT/wasm-apps/trend/trend.c" "$SDK"

{
    echo "/* Generated by tests/unit/gen-wasm-vectors.sh from tests/unit/wasm/ and wasm-apps/: do not edit. */"
    echo "#pragma once"
    for w in "$TMP"/*.wasm; do
        name="$(basename "$w" .wasm)"
        python3 -I -c '
import sys
d = open(sys.argv[1], "rb").read()
print("static const unsigned char w_%s[] = {" % sys.argv[2])
for i in range(0, len(d), 16):
    print("    " + ", ".join("0x%02x" % b for b in d[i:i + 16]) + ",")
print("};")' "$w" "$name"
    done
} > "$OUT"
echo "wrote $OUT ($(ls "$TMP"/*.wasm | wc -l | tr -d ' ') modules)"
