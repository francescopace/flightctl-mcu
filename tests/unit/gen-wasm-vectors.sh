#!/usr/bin/env bash
# Writes tests/unit/wasm_vectors.h: the WASM modules of tests/unit/wasm/ and
# the example apps of wasm-apps/, built with wasm-apps/build.sh's flags
# against wasm-apps/sdk/fc_app.h, as C arrays for test_apps.c.
# Needs clang with the wasm32 target and wasm-ld. Usage: tests/unit/gen-wasm-vectors.sh
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
OUT="$ROOT/tests/unit/wasm_vectors.h"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT
FLAGS=(--target=wasm32 -mcpu=mvp -O2 -nostdlib -Wall -Wextra -Werror -Wno-unused-parameter
       -Wl,--no-entry -Wl,--export=__heap_base -Wl,--export=__data_end -Wl,--stack-first
       -Wl,-z,stack-size=1024 -Wl,--initial-memory=65536 -Wl,--max-memory=65536 -Wl,--strip-all)

build() { # name source include [defines...]
    local name="$1" src="$2" inc="$3"
    shift 3
    clang "${FLAGS[@]}" -I"$inc" "$@" -o "$TMP/$name.wasm" "$src"
}

SDK="$ROOT/wasm-apps/sdk"
for src in "$ROOT"/tests/unit/wasm/*.c; do
    name="$(basename "$src" .c)"
    if [[ "$name" == t_tail ]]; then
        build "$name" "$src" "$SDK" -mtail-call
    elif [[ "$name" == t_libc || "$name" == t_libcloop || "$name" == t_libcmix || "$name" == t_libcmath || "$name" == t_malloc ]]; then
        build "$name" "$src" "$SDK" -I"$SDK/libc" -Wl,--allow-undefined-file="$SDK/libc/libc.syms"
    elif [[ "$name" == t_ctor* ]]; then
        build "$name" "$src" "$SDK" -Wl,--export=__wasm_call_ctors
    elif [[ "$name" == t_libcoob ]]; then
        for c in 1 2 3 4 5; do
            build "${name}_$c" "$src" "$SDK" -I"$SDK/libc" -Wl,--allow-undefined-file="$SDK/libc/libc.syms" -DCASE=$c
        done
    else
        build "$name" "$src" "$SDK"
    fi
done
# The example apps with the C library, as wasm-apps/build.sh builds them.
LIBC=(-I"$SDK/libc" -Wl,--allow-undefined-file="$SDK/libc/libc.syms")
build app_alarm_v1 "$ROOT/wasm-apps/alarm/alarm.c" "$SDK" "${LIBC[@]}" -DFC_ALARM_SOLID_DEMO=1
build app_alarm_v2 "$ROOT/wasm-apps/alarm/alarm.c" "$SDK" "${LIBC[@]}"
build app_sampler "$ROOT/wasm-apps/sampler/sampler.c" "$SDK" "${LIBC[@]}"
build app_localalarm "$ROOT/wasm-apps/localalarm/localalarm.c" "$SDK" "${LIBC[@]}"
build app_battery "$ROOT/wasm-apps/battery/battery.c" "$SDK" "${LIBC[@]}"
build app_trend "$ROOT/wasm-apps/trend/trend.c" "$SDK" "${LIBC[@]}"
build app_hwcheck "$ROOT/wasm-apps/hwcheck/hwcheck.c" "$SDK" "${LIBC[@]}"
build app_mqttdemo "$ROOT/wasm-apps/mqttdemo/mqttdemo.c" "$SDK" "${LIBC[@]}"
build app_tinyml "$ROOT/wasm-apps/tinyml/tinyml.c" "$SDK" "${LIBC[@]}"
build app_tinymlp "$ROOT/wasm-apps/tinymlp/tinymlp.c" "$SDK" "${LIBC[@]}" -I"$ROOT/wasm-apps/tinymlp" -Wno-unused-function # emlearn's eml_error_str

{
    echo "/* Generated by tests/unit/gen-wasm-vectors.sh from tests/unit/wasm/ and wasm-apps/: do not edit. */"
    echo "#pragma once"
    for w in "$TMP"/*.wasm; do
        name="$(basename "$w" .wasm)"
        python3 -I -c '
import sys
d = open(sys.argv[1], "rb").read()
print("static const unsigned char w_%s[] = {" % sys.argv[2])
for i in range(0, len(d), 16):
    print("    " + ", ".join("0x%02x" % b for b in d[i:i + 16]) + ",")
print("};")' "$w" "$name"
    done
} > "$OUT"
echo "wrote $OUT ($(ls "$TMP"/*.wasm | wc -l | tr -d ' ') modules)"
