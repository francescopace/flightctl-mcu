#!/usr/bin/env python3
"""Writes tests/unit/delta_vectors.h: an old image, a new one and the detools
patches between them, for test_oci.c. Run with a python that has detools
(build/detools-venv/bin/python, which tools/fw-push.py --delta-from makes):

    build/detools-venv/bin/python tests/unit/gen-delta-vectors.py
"""
import io
import os

import detools


def image(seed, size):
    """Bytes with some structure, like code: repeated words with small changes."""
    out = bytearray()
    x = seed
    while len(out) < size:
        x = (x * 1103515245 + 12345) & 0x7FFFFFFF
        out += bytes([0x13 + (x >> 8) % 7, (x >> 16) & 0xFF, 0x40, (len(out) >> 4) & 0xFF])
    return bytes(out[:size])


def patch(old, new, window, lookahead):
    p = io.BytesIO()
    detools.create_patch(io.BytesIO(old), io.BytesIO(new), p, compression="heatshrink", patch_type="sequential",
                         heatshrink_window_sz2=window, heatshrink_lookahead_sz2=lookahead)
    return p.getvalue()


def c_array(name, data):
    rows = [", ".join(f"0x{b:02x}" for b in data[i:i + 16]) for i in range(0, len(data), 16)]
    return f"static const unsigned char {name}[{len(data)}] = {{\n    " + ",\n    ".join(rows) + ",\n};\n"


old = image(1, 3000)
# The new image: a changed word, an insertion that shifts the rest, new bytes
# at the end.
new = bytearray(old)
new[100:104] = b"\xde\xad\xbe\xef"
new[1500:1500] = image(7, 96)
new += image(9, 200)
new = bytes(new)
out = '/* Generated by gen-delta-vectors.py with detools %s: do not edit. */\n' % detools.__version__
out += c_array("delta_old", old) + c_array("delta_new", new)
out += "/* old -> new: sequential, heatshrink, window 2^12, lookahead 2^8 */\n" + c_array("delta_patch", patch(old, new, 12, 8))
out += "/* the same with a window of 2^13: more than the device allows */\n" + c_array("delta_patch_w13", patch(old, new, 13, 8))
path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "delta_vectors.h")
with open(path, "w") as f:
    f.write(out)
print(f"{path}: old {len(old)}, new {len(new)}, patch {len(patch(old, new, 12, 8))}")
