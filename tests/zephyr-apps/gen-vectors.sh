#!/usr/bin/env bash
# Writes tests/zephyr-apps/src/vectors.h: the modules of tests/zephyr-apps/wasm/,
# built as tests/unit/gen-wasm-vectors.sh builds those of tests/unit (which
# tests/zephyr-apps also runs, from tests/unit/wasm_vectors.h).
# Needs clang with the wasm32 target and wasm-ld.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
OUT="$ROOT/tests/zephyr-apps/src/vectors.h"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT
SDK="$ROOT/wasm-apps/sdk"
FLAGS=(--target=wasm32 -mcpu=mvp -O2 -nostdlib -Wall -Wextra -Werror -Wno-unused-parameter
       -Wl,--no-entry -Wl,--export=__heap_base -Wl,--export=__data_end -Wl,--stack-first
       -Wl,-z,stack-size=1024 -Wl,--initial-memory=65536 -Wl,--max-memory=65536 -Wl,--strip-all
       -I"$SDK" -I"$SDK/libc" -Wl,--allow-undefined-file="$SDK/libc/libc.syms")
for src in "$ROOT"/tests/zephyr-apps/wasm/*.c; do
    clang "${FLAGS[@]}" -o "$TMP/$(basename "$src" .c).wasm" "$src"
done
{
    echo "/* Generated by tests/zephyr-apps/gen-vectors.sh from tests/zephyr-apps/wasm/: do not edit. */"
    echo "#pragma once"
    for w in "$TMP"/*.wasm; do
        python3 -I -c '
import sys
d = open(sys.argv[1], "rb").read()
print("static const unsigned char w_%s[] = {" % sys.argv[2])
for i in range(0, len(d), 16):
    print("    " + ", ".join("0x%02x" % b for b in d[i:i + 16]) + ",")
print("};")' "$w" "$(basename "$w" .wasm)"
    done
} > "$OUT"
echo "wrote $OUT"
