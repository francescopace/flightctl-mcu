#!/usr/bin/env bash
# Fetches the blink of wasm3-arduino as it is published, unmodified
# (github.com/wasm3/wasm3-arduino, MIT, examples_pio/Wasm_Advanced/wasm_apps,
# commit 0dcff083), for wasm-apps/push.sh. Four builds of the same app:
#   rust            283 B, 64 KB of memory shrunk to what it uses
#   cpp             369 B, 64 KB of memory kept whole (no __heap_base)
#   assemblyscript  2.2 KB, 64 KB kept whole
#   tinygo          5.2 KB
# Each imports only from "arduino" (pinMode, digitalWrite, delay, getPinLED,
# print...) and exports _start(), which blinks the board's LED forever: the
# device runs it once, with no budget (docs/APPS.md). Give the app
# FC_ALLOW "led0". Each is checked against its SHA-256 and written to
# wasm-apps/build/arduino-<build>/arduino.wasm.
# Usage: wasm-apps/arduino/fetch.sh [rust|cpp|assemblyscript|tinygo]...   (default: all)
#   then: wasm-apps/push.sh arduino rust [tag] [REGISTRY]
# VECTORS=1 also writes the four as C arrays into tests/unit/arduino_vectors.h.
set -euo pipefail
DIR="$(cd "$(dirname "$0")/.." && pwd)"
BASE=https://raw.githubusercontent.com/wasm3/wasm3-arduino/0dcff083f369f89d7bd5d434d60e63d789fab133/examples_pio/Wasm_Advanced/wasm_apps
fetch() {
    local build="$1" sha out="$DIR/build/arduino-$1"
    case "$build" in
    rust) sha=247b2d4449acfe3f1d82107b9abb93c73fcc6b6ac4283d012097b12d6df5101d ;;
    cpp) sha=01773158b1a55c99930923151d7c3ac62ee712ff6cbe6283eb71c009e0fb48de ;;
    assemblyscript) sha=c655dae2a733080a9055c8c8a09342156ee14717da0eb3c9fcbbb3c11deecfef ;;
    tinygo) sha=8c1d7d14a03ddbe09eb1511868a16498b3331a5ccef21e3519324901b92c41be ;;
    *) echo "unknown build $build (rust, cpp, assemblyscript, tinygo)" >&2; return 1 ;;
    esac
    mkdir -p "$out"
    curl -sSfL -o "$out/arduino.wasm" "$BASE/$build/app.wasm"
    local got
    got="$(shasum -a 256 "$out/arduino.wasm" | cut -d' ' -f1)"
    if [[ "$got" != "$sha" ]]; then
        echo "arduino $build: SHA-256 $got, expected $sha" >&2
        rm -f "$out/arduino.wasm"
        return 1
    fi
    echo "arduino $build: $(wc -c < "$out/arduino.wasm" | tr -d ' ') bytes in $out"
}
[[ $# -gt 0 ]] || set -- rust cpp assemblyscript tinygo
for b in "$@"; do
    fetch "$b"
done
if [[ -n "${VECTORS:-}" ]]; then
    for b in rust cpp assemblyscript tinygo; do
        fetch "$b" >/dev/null
    done
    python3 -I - "$DIR/build" "$DIR/../tests/unit/arduino_vectors.h" <<'PY'
import sys
build, out = sys.argv[1], sys.argv[2]
with open(out, "w") as f:
    f.write("/* Generated by wasm-apps/arduino/fetch.sh (VECTORS=1): do not edit. The blink of\n"
            " * wasm3-arduino as published (MIT, github.com/wasm3/wasm3-arduino, commit 0dcff083). */\n"
            "#pragma once\n")
    for b in ("rust", "cpp", "assemblyscript", "tinygo"):
        d = open("%s/arduino-%s/arduino.wasm" % (build, b), "rb").read()
        f.write("static const unsigned char w_arduino_%s[] = {\n" % b)
        for i in range(0, len(d), 16):
            f.write("    " + ", ".join("0x%02x" % x for x in d[i:i + 16]) + ",\n")
        f.write("};\n")
PY
    echo "wrote tests/unit/arduino_vectors.h"
fi
