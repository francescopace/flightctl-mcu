#!/usr/bin/env python3
"""Trains the "tinymlp" app's model and writes it as C with emlearn.

The same task as wasm-apps/tinyml, on the same synthetic data and features
(tinyml/train.py and tinyml/features.h), with a small neural network instead
of a random forest: a multi-layer perceptron with 3 inputs, hidden layers of
16 and 8 with tanh, and a softmax over the four classes. emlearn's eml_net
computes it with expf, logf and tanhf, which the device has for apps
(wasm-apps/sdk/libc/math.h). The features go in as hundredths, so that they
are about 1, as such a network wants.

Writes, next to this script:
  model.h     the network, as emlearn writes it (method "loadable"), with
              mlp_predict()
  eml_*.h     the emlearn headers model.h needs (eml_net.h and the three it
              includes), unmodified, with emlearn's licence (EMLEARN-LICENSE.md);
              build.sh puts the app's directory on the include path
  vectors.h   test windows, their features and scikit-learn's prediction, for
              tests/unit/test_tinyml.c

Needs tinyml's requirements.txt, and runs as tinyml/train.py does:
  /tmp/tinyml/bin/python wasm-apps/tinymlp/train.py
"""
import os
import shutil
import sys
import tempfile

import emlearn
import numpy as np
import sklearn
from sklearn.neural_network import MLPClassifier

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "tinyml"))
import train as tinyml  # noqa: E402

SCALE = np.float32(0.01)
HIDDEN = (16, 8)
HEADERS = ["eml_net.h", "eml_common.h", "eml_log.h", "eml_net_common.h"]


def main():
    rng = np.random.default_rng(tinyml.SEED)
    train_w, train_y = tinyml.dataset(rng, tinyml.PER_CLASS)
    test_w, test_y = tinyml.dataset(rng, 50)
    train_x = np.array([tinyml.features(w) for w in train_w], dtype=np.int16)
    test_x = np.array([tinyml.features(w) for w in test_w], dtype=np.int16)

    model = MLPClassifier(hidden_layer_sizes=HIDDEN, activation="tanh", max_iter=2000,
                          random_state=tinyml.SEED)
    model.fit(train_x.astype(np.float32) * SCALE, train_y)
    pred = model.predict(test_x.astype(np.float32) * SCALE)
    print("emlearn %s, scikit-learn %s, numpy %s: MLP 3-%d-%d-4, %d parameters, test accuracy %.3f"
          % (emlearn.__version__, sklearn.__version__, np.__version__, HIDDEN[0], HIDDEN[1],
             sum(w.size for w in model.coefs_) + sum(b.size for b in model.intercepts_),
             (pred == test_y).mean()), file=sys.stderr)

    with tempfile.TemporaryDirectory() as tmp:  # emlearn builds a test program in ./tmp
        cwd = os.getcwd()
        os.chdir(tmp)
        try:
            emlearn.convert(model, method="loadable").save(file=os.path.join(HERE, "model.h"), name="mlp")
        finally:
            os.chdir(cwd)
    src = os.path.dirname(emlearn.__file__)
    for h in HEADERS:
        shutil.copyfile(os.path.join(src, h), os.path.join(HERE, h))
    lic = [os.path.join(os.path.dirname(src), d, "licenses", "LICENSE.md")
           for d in os.listdir(os.path.dirname(src)) if d.startswith("emlearn-%s." % emlearn.__version__)]
    shutil.copyfile(lic[0], os.path.join(HERE, "EMLEARN-LICENSE.md"))

    with open(os.path.join(HERE, "vectors.h"), "w") as out:
        out.write("/* Generated by wasm-apps/tinymlp/train.py (emlearn %s, scikit-learn %s, numpy %s): do not edit.\n"
                  " * tinyml's test windows' features (tinyml/vectors.h) and the class scikit-learn's\n"
                  " * network gives each. */\n"
                  % (emlearn.__version__, sklearn.__version__, np.__version__))
        out.write("#pragma once\n#include <stdint.h>\n\n")
        out.write("static const int32_t mlp_window_class[] = {%s};\n"
                  % ", ".join(str(int(c)) for c in pred))


if __name__ == "__main__":
    main()
